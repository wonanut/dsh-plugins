/**
 * Builds client.js from src/*.js.
 *
 * The Web Client loads one plain-JS module per plugin: a lazy factory registered
 * on window.__ModuleLoader__. We concatenate the numbered source files into that
 * factory and embed every source file as a JSON string so the in-app source
 * browser shows exactly the code that is running.
 *
 * Usage: node build.mjs            → writes client.js and syntax-checks it
 *        node build.mjs --check    → syntax-check only
 */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const moduleId = manifest.name;

/** Build order matters: later files see earlier declarations in one scope. */
const FILES = [
  ['00-core.js', '常量、token 估算与通用工具'],
  ['10-engine.js', '会话 / 记忆 / 上下文 / 压缩 / createLab'],
  ['20-tools.js', '工具注册表与四个工具'],
  ['30-llm.js', '规则驱动的模拟 LLM'],
  ['40-ui-kit.js', '全局样式与 UI 原语'],
  ['45-real-client.js', '真实模型客户端：状态与模型请求'],
  ['50-tui.js', '模拟 TUI 终端'],
  ['60-inspector.js', '流转 / 上下文 / 记忆检查器'],
  ['65-dataflow.js', 'Agent 数据流转视图（回放）'],
  ['70-docs.js', 'Agent 原理页'],
  ['80-source.js', '源码浏览器'],
  ['90-page.js', '页面外壳与会话栏'],
  ['95-apply.js', 'slot 注册入口'],
];

const readSource = ([file, role]) => ({
  id: file.replace(/\.js$/, ''),
  name: file,
  role,
  code: fs.readFileSync(path.join(root, 'src', file), 'utf8'),
});

const bodySources = FILES.map(readSource).filter((item) => item.code.trim().length > 0);

const hostSource = {
  id: 'index-host',
  name: 'index.js (Host 半侧)',
  role: '真实模型路由：status / complete（调用 DSH 当前 DeepSeek 模型）',
  code: fs.readFileSync(path.join(root, 'index.js'), 'utf8'),
};
const sources = bodySources.concat([hostSource]);
const missing = FILES.filter(([file]) => !fs.existsSync(path.join(root, 'src', file)));
if (missing.length > 0) {
  console.warn('[build] waiting for source files:', missing.map(([file]) => file).join(', '));
}

const body = bodySources
  .map((source) => `/* ── ${source.name} · ${source.role} ── */\n${source.code}`)
  .join('\n\n');

const output = `/* Generated by build.mjs from src/*.js — do not edit by hand. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(moduleId)},
  factory(require) {
    const React = require('react');
    const e = React.createElement;
    const { useState, useEffect, useMemo, useRef, useCallback } = React;
    const SOURCES = ${JSON.stringify(sources)};

${body}

    return { inject: ['slots'], apply };
  },
});
`;

const target = path.join(root, 'client.js');

if (process.argv.includes('--check')) {
  new vm.Script(output, { filename: target });
  console.log('[build] syntax OK,', output.length, 'bytes (not written)');
  process.exit(0);
}

fs.writeFileSync(target, output);
new vm.Script(output, { filename: target });
console.log(`[build] wrote ${target} (${output.length} bytes, ${sources.length} sources)`);
